"""
tools.prebake_voicelines -- Mass-generate Aura voicelines as WAV files.

Goal: kill the "I keep hearing the same canned line" problem. Instead of
synthesising a phrase live every time Aura wants to greet you, we build
a giant pool of pre-baked WAVs (target: 10k+) and pick one at random.

Each line is generated by the in-process Qwen LLM at high temperature,
synthesised with the trained Piper voice, and written to:

    data/voicelines/<category>/<hash>.wav

with a manifest at data/voicelines/manifest.json mapping category to
{hash, text, style, wav}. The script is resumable -- re-running it
skips lines already in the manifest and tops up to --target.

Categories (name-agnostic by design -- the WAV is fixed at bake time,
so a phrase like "Hey {name}, what's up" can't be parameterized; we
prebake lines that don't reference the user's name and let live-LLM
paths handle name-personalised greetings):

    welcome_guest       -- anonymous user post-boot
    welcome_returning   -- known user post-boot (no name)
    welcome_briefing    -- known user with briefing waiting
    idle_prompt         -- proactive conversation starter

Run on the puck (LLM model is in-process):

    cd /home/paul/Aura4/aura && \
        python3 -u ../tools/prebake_voicelines.py --target 2500 --all

Resume / top-up later by re-running the same command.
"""

from __future__ import annotations

