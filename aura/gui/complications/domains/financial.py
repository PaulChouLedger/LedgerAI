"""
gui.complications.domains.financial -- Daily Brief overlay.

Sci-fi command-center HUD that surfaces the latest pending briefing
(generated by services.perpetual) along with dynamic visualisations
extracted from recent briefings:

  * Top arc:        "DAILY BRIEF" header + date / user
  * Headline band:  the first sentence of `insight` revealed with a
                    typewriter effect, ending in a blinking cursor
  * Center:         orbital "topic constellation" — the most-frequent
                    keywords across recent briefings rendered as nodes
                    on concentric orbits, linked by faint lines, sized
                    by frequency, slowly rotating
  * Around center:  four sci-fi gauges (SENTIMENT / URGENCY / NOVELTY
                    / CONFIDENCE) computed from the insight text
  * Bottom band:    ticker tape — supporting-evidence bullets scrolling
                    right-to-left
  * Background:     deep navy with a faint hexagonal grid and a vertical
                    scan line that passes every ~7 s

Class name + `name = "Financial"` are kept for registry compatibility
with the existing dock; only the `label` is renamed to "Daily Brief".
"""

