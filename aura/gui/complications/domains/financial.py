_WORD_RE = re.compile(r"\b[a-zA-Z][a-zA-Z\-']{2,}\b")


def _read_briefing_json(path: Path) -> Optional[dict]:
    try:
        with open(path) as f:
            return json.load(f)
    except Exception:
        return None


def _load_recent_briefings(limit: int = 12) -> List[dict]:
    """Return up to *limit* most-recent JSON briefings."""
    if not _BRIEFINGS_DIR.is_dir():
        return []
    files = sorted(
        _BRIEFINGS_DIR.glob("*.json"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )[:limit]
    out = []
    for p in files:
        b = _read_briefing_json(p)
        if b:
            out.append(b)
    return out


def _extract_topics(text: str, top_n: int = 8) -> List[Tuple[str, int]]:
    """Most-frequent meaningful words in *text*."""
    counts: dict[str, int] = {}
    for w in _WORD_RE.findall(text or ""):
        wl = w.lower()
        if wl in _STOPWORDS or len(wl) < 4:
            continue
        counts[wl] = counts.get(wl, 0) + 1
    pairs = sorted(counts.items(), key=lambda kv: -kv[1])
    return pairs[:top_n]


def _sentiment_ratio(text: str) -> float:
    """Crude positive/negative split → 0..1 (0 = bleak, 1 = euphoric)."""
    pos = neg = 0
    for w in _WORD_RE.findall(text or ""):
        wl = w.lower()
        if wl in _POS_WORDS:
            pos += 1
        elif wl in _NEG_WORDS:
            neg += 1
    if pos + neg == 0:
        return 0.55  # default to a slight positive idle
    return clamp(pos / (pos + neg), 0.0, 1.0)


def _urgency_score(briefing: Optional[dict]) -> float:
    """Synthetic: knowledge gaps + supporting-evidence count + age."""
    if not briefing:
        return 0.30
    gaps = len(briefing.get("knowledge_gaps") or [])
    ev = len(briefing.get("supporting_evidence") or [])
    age_h = max(0.0, (time.time() - briefing.get("generated_at", time.time())) / 3600.0)
    # More gaps + more evidence → higher urgency, decays with age
    raw = (0.10 * ev) + (0.12 * gaps) + (0.30 / (1.0 + age_h * 0.3))
    return clamp(raw, 0.05, 1.0)


def _novelty_score(briefing: Optional[dict], topics: List[Tuple[str, int]]) -> float:
    """Rough proxy: more unique top topics → more novel."""
    if not topics:
        return 0.40
    # Diversity = count of unique topics with >=1 hit.
    unique = len([w for w, c in topics if c >= 1])
    return clamp(unique / 10.0 + 0.2, 0.0, 1.0)


def _first_sentence(text: str) -> str:
    """Pick a one-line headline — first sentence trimmed to ~110 chars."""
    if not text:
        return ""
    text = text.strip()
    # Split on first sentence terminator
    m = re.search(r"[.!?](\s|$)", text)
    if m:
        end = m.end()
        first = text[:end].strip()
    else:
        first = text
    if len(first) > 130:
        first = first[:127].rstrip() + "…"
    return first


