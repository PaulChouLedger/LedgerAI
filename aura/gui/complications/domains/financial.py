def _draw_hex_grid(p, cx, cy, R, t, alpha):
    """Faint hexagonal grid backdrop — drifts very slowly."""
    drift_x = (t * 4.0) % (R * 0.18)
    drift_y = (t * 1.5) % (R * 0.16)
    pen = QPen(QColor(_HUD_GRID.red(), _HUD_GRID.green(), _HUD_GRID.blue(), alpha))
    pen.setWidthF(max(0.35, R * 0.0018))
    p.setPen(pen)
    p.setBrush(Qt.NoBrush)
    side = R * 0.045
    h = side * math.sqrt(3.0) / 2.0
    rows = int((2 * R) / h) + 2
    cols = int((2 * R) / (1.5 * side)) + 2
    x0 = cx - R - drift_x
    y0 = cy - R - drift_y
    for r in range(rows):
        for c in range(cols):
            cxh = x0 + c * 1.5 * side
            cyh = y0 + r * 2 * h + (h if c % 2 else 0)
            # Skip if outside the dial
            if (cxh - cx) ** 2 + (cyh - cy) ** 2 > (R * 1.05) ** 2:
                continue
            path = QPainterPath()
            for k in range(6):
                ang = math.pi / 3.0 * k
                x = cxh + side * math.cos(ang)
                y = cyh + side * math.sin(ang)
                if k == 0:
                    path.moveTo(x, y)
                else:
                    path.lineTo(x, y)
            path.closeSubpath()
            p.drawPath(path)


def _draw_scan_line(p, cx, cy, R, t, trans):
    """Vertical scan line that passes top→bottom every ~7 s."""
    period = 7.0
    phase = (t % period) / period
    y = (cy - R) + phase * (2 * R)
    h_band = R * 0.16
    grad = QLinearGradient(0, y - h_band, 0, y + h_band)
    grad.setColorAt(0.0, QColor(0, 0, 0, 0))
    grad.setColorAt(0.5, QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                  _HUD_PRIMARY.blue(), int(60 * trans)))
    grad.setColorAt(1.0, QColor(0, 0, 0, 0))
    p.setPen(Qt.NoPen)
    p.setBrush(QBrush(grad))
    p.drawRect(QRectF(cx - R, y - h_band, 2 * R, 2 * h_band))


def _draw_arc_text(p, cx, cy, text, radius, center_deg, font, color,
                   spacing_deg=6.5, flip=False):
    chars = list(text)
    if flip:
        chars = chars[::-1]
    n = len(chars)
    if n == 0:
        return
    span = (n - 1) * spacing_deg
    start = center_deg - span * 0.5
    p.save()
    p.setFont(font)
    fm = p.fontMetrics()
    ch_h = fm.height()
    extra_rot = 180.0 if flip else 0.0
    for i, ch in enumerate(chars):
        a = math.radians(start + i * spacing_deg)
        x = cx + radius * math.cos(a)
        y = cy + radius * math.sin(a)
        ch_w = max(fm.horizontalAdvance(ch), ch_h)
        p.save()
        p.translate(x, y)
        p.rotate(math.degrees(a) + 90.0 + extra_rot)
        rect = QRectF(-ch_w * 0.7, -ch_h * 0.6, ch_w * 1.4, ch_h * 1.2)
        p.setPen(color)
        p.drawText(rect, Qt.AlignCenter, ch)
        p.restore()
    p.restore()


def _draw_gauge(p, cx, cy, radius, label, value, color, trans, t):
    """Sci-fi mini gauge — semicircular arc 210°→-30° with a needle.

    `value` is 0..1. `color` is the active arc color.
    """
    # Outer track
    track_pen = QPen(QColor(70, 110, 150, int(120 * trans)))
    track_pen.setWidthF(max(1.2, radius * 0.07))
    track_pen.setCapStyle(Qt.RoundCap)
    p.setPen(track_pen)
    p.setBrush(Qt.NoBrush)
    rect = QRectF(cx - radius, cy - radius, 2 * radius, 2 * radius)
    # Qt arc: degrees * 16
    p.drawArc(rect, int(210 * 16), int(-240 * 16))

    # Active arc (filled fraction of track)
    active_pen = QPen(color)
    active_pen.setWidthF(max(1.6, radius * 0.09))
    active_pen.setCapStyle(Qt.RoundCap)
    p.setPen(active_pen)
    sweep_deg = -240 * value
    p.drawArc(rect, int(210 * 16), int(sweep_deg * 16))

    # Tick marks on track
    tick_pen = QPen(QColor(140, 180, 220, int(110 * trans)))
    tick_pen.setWidthF(max(0.5, radius * 0.025))
    p.setPen(tick_pen)
    for k in range(11):
        ang = math.radians(210 - k * 24)
        r1 = radius - radius * 0.08
        r2 = radius - radius * 0.02
        x1 = cx + r1 * math.cos(ang)
        y1 = cy + r1 * math.sin(ang)
        x2 = cx + r2 * math.cos(ang)
        y2 = cy + r2 * math.sin(ang)
        p.drawLine(QPointF(x1, y1), QPointF(x2, y2))

    # Pulse halo on active arc tip
    tip_ang = math.radians(210 + sweep_deg)
    tip_x = cx + radius * math.cos(tip_ang)
    tip_y = cy + radius * math.sin(tip_ang)
    pulse = 0.6 + 0.4 * math.sin(t * 2.5)
    halo = QRadialGradient(QPointF(tip_x, tip_y), radius * 0.45)
    halo.setColorAt(0.0, QColor(color.red(), color.green(), color.blue(),
                                 int(160 * pulse * trans)))
    halo.setColorAt(1.0, QColor(0, 0, 0, 0))
    p.setPen(Qt.NoPen)
    p.setBrush(QBrush(halo))
    p.drawEllipse(QPointF(tip_x, tip_y), radius * 0.45, radius * 0.45)

    # Numeric readout
    num_font = QFont("Helvetica Neue", max(8, int(radius * 0.40)))
    num_font.setWeight(QFont.DemiBold)
    p.setFont(num_font)
    p.setPen(_HUD_TEXT)
    p.drawText(QRectF(cx - radius, cy - radius * 0.18, 2 * radius, radius * 0.45),
               Qt.AlignCenter, f"{int(value * 100):02d}")

    # Label below
    lbl_font = QFont("Helvetica Neue", max(6, int(radius * 0.18)))
    lbl_font.setLetterSpacing(QFont.PercentageSpacing, 145)
    lbl_font.setWeight(QFont.Medium)
    p.setFont(lbl_font)
    p.setPen(_HUD_TEXT_DIM)
    p.drawText(QRectF(cx - radius * 1.5, cy + radius * 0.30, 3 * radius, radius * 0.40),
               Qt.AlignCenter, label)


def _draw_constellation(p, cx, cy, R, topics, t, trans):
    """Topic constellation — keywords as glowing nodes orbiting the
    center, linked by faint lines."""
    if not topics:
        return
    n = min(len(topics), 8)
    # Two concentric orbits
    orbit_r1 = R * 0.30
    orbit_r2 = R * 0.46
    speed1 = 0.12
    speed2 = -0.08

    # Pre-compute positions
    positions = []
    weights = [c for _, c in topics[:n]]
    max_w = max(weights) if weights else 1
    for i, (word, count) in enumerate(topics[:n]):
        # Even indices on inner orbit, odd on outer
        if i % 2 == 0:
            r = orbit_r1
            ang = (i / max(1, (n + 1) // 2)) * 2 * math.pi + t * speed1
        else:
            r = orbit_r2
            ang = (i / max(1, n // 2)) * 2 * math.pi + t * speed2 + 0.4
        x = cx + r * math.cos(ang)
        y = cy + r * math.sin(ang)
        positions.append((x, y, word, count))

    # Connecting lines (each node to its 2 nearest neighbours)
    line_pen = QPen(QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                            _HUD_PRIMARY.blue(), int(50 * trans)))
    line_pen.setWidthF(max(0.5, R * 0.0018))
    p.setPen(line_pen)
    p.setBrush(Qt.NoBrush)
    for i, (x1, y1, _, _) in enumerate(positions):
        # Distances to all others
        dists = []
        for j, (x2, y2, _, _) in enumerate(positions):
            if i == j:
                continue
            d = math.hypot(x2 - x1, y2 - y1)
            dists.append((d, j))
        dists.sort()
        for _, j in dists[:2]:
            x2, y2, _, _ = positions[j]
            p.drawLine(QPointF(x1, y1), QPointF(x2, y2))

    # Nodes + labels
    for i, (x, y, word, count) in enumerate(positions):
        # Node size by frequency
        sz = R * (0.018 + 0.030 * (count / max_w))
        # Halo
        halo = QRadialGradient(QPointF(x, y), sz * 4)
        halo.setColorAt(0.0, QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                     _HUD_PRIMARY.blue(), int(150 * trans)))
        halo.setColorAt(1.0, QColor(0, 0, 0, 0))
        p.setPen(Qt.NoPen)
        p.setBrush(QBrush(halo))
        p.drawEllipse(QPointF(x, y), sz * 4, sz * 4)
        # Body
        body = QRadialGradient(QPointF(x - sz * 0.3, y - sz * 0.3), sz * 1.4)
        body.setColorAt(0.0, QColor(255, 252, 240, int(245 * trans)))
        body.setColorAt(0.7, QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                     _HUD_PRIMARY.blue(), int(230 * trans)))
        body.setColorAt(1.0, QColor(40, 90, 130, int(190 * trans)))
        p.setBrush(QBrush(body))
        p.drawEllipse(QPointF(x, y), sz, sz)
        # Label (offset radially outward)
        ang = math.atan2(y - cy, x - cx)
        lx = x + math.cos(ang) * (sz + R * 0.04)
        ly = y + math.sin(ang) * (sz + R * 0.04)
        f = QFont("Helvetica Neue", max(7, int(R * 0.030)))
        f.setLetterSpacing(QFont.PercentageSpacing, 130)
        f.setWeight(QFont.Medium)
        p.setFont(f)
        p.setPen(QColor(_HUD_TEXT.red(), _HUD_TEXT.green(), _HUD_TEXT.blue(),
                         int(225 * trans)))
        rect = QRectF(lx - R * 0.15, ly - R * 0.04, R * 0.30, R * 0.08)
        p.drawText(rect, Qt.AlignCenter, word.upper())


def _draw_ticker_tape(p, cx, cy, R, items, t, trans):
    """Bottom band — supporting-evidence bullets scrolling right→left."""
    if not items:
        return
    band_y = cy + R * 0.78
    band_h = R * 0.10
    # Band background — subtle gradient
    grad = QLinearGradient(cx - R, 0, cx + R, 0)
    grad.setColorAt(0.0, QColor(0, 0, 0, 0))
    grad.setColorAt(0.10, QColor(_HUD_BG_DEEP.red(), _HUD_BG_DEEP.green(),
                                   _HUD_BG_DEEP.blue(), int(180 * trans)))
    grad.setColorAt(0.90, QColor(_HUD_BG_DEEP.red(), _HUD_BG_DEEP.green(),
                                   _HUD_BG_DEEP.blue(), int(180 * trans)))
    grad.setColorAt(1.0, QColor(0, 0, 0, 0))
    p.setPen(Qt.NoPen)
    p.setBrush(QBrush(grad))
    p.drawRect(QRectF(cx - R, band_y - band_h * 0.5, 2 * R, band_h))

    # Hairline edges
    edge_pen = QPen(QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                            _HUD_PRIMARY.blue(), int(80 * trans)))
    edge_pen.setWidthF(max(0.5, R * 0.0014))
    p.setPen(edge_pen)
    p.drawLine(QPointF(cx - R * 0.85, band_y - band_h * 0.5),
               QPointF(cx + R * 0.85, band_y - band_h * 0.5))
    p.drawLine(QPointF(cx - R * 0.85, band_y + band_h * 0.5),
               QPointF(cx + R * 0.85, band_y + band_h * 0.5))

    # Compose ticker text
    sep = "   ◇   "
    ticker_text = sep.join(items) + sep
    f = QFont("Helvetica Neue", max(8, int(R * 0.035)))
    f.setWeight(QFont.Medium)
    f.setLetterSpacing(QFont.PercentageSpacing, 125)
    p.setFont(f)
    fm = p.fontMetrics()
    text_w = fm.horizontalAdvance(ticker_text)
    if text_w == 0:
        return
    # Scrolling offset
    scroll_speed = R * 0.18         # px / s
    offset = (t * scroll_speed) % text_w
    start_x = cx + R - offset
    p.setPen(QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                     _HUD_PRIMARY.blue(), int(220 * trans)))
    # Draw two copies for seamless wrap
    p.drawText(QPointF(start_x, band_y + fm.descent() * 0.3), ticker_text)
    p.drawText(QPointF(start_x - text_w, band_y + fm.descent() * 0.3), ticker_text)


