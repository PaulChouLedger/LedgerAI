class FinancialComplication(BaseDomainComplication):
    name = "Financial"        # registry compatibility with existing dock
    label = "Daily Brief"     # visible label — was "Financial"
    category = "Topics"

    def __init__(self, bus):
        super().__init__(bus)
        self._t0: float = 0.0
        # Cached extracted data
        self._cache_ts: float = 0.0
        self._headline: str = ""
        self._topics: List[Tuple[str, int]] = []
        self._evidence: List[str] = []
        self._sentiment: float = 0.55
        self._urgency: float = 0.30
        self._novelty: float = 0.40
        self._confidence: float = 0.50
        self._date_label: str = ""
        self._user_label: str = ""
        # Audio playback handle (for the briefing's pre-synthesised audio)
        self._audio_proc = None

    # ── Lifecycle hooks expected by the overlay routing ───────────────

    def play_audio(self):
        """If the pending briefing has a pre-synth WAV, play it."""
        from core.state import state
        b = state.pending_briefing
        if not b:
            return
        wav = b.get("audio_path")
        if not wav or not os.path.exists(wav):
            return
        try:
            from core.config import ALSA_PLAYBACK_DEVICE
            import subprocess
            self._audio_proc = subprocess.Popen(
                ["aplay", "-D", ALSA_PLAYBACK_DEVICE, "-q", wav],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
        except Exception:
            self._audio_proc = None

    def stop_audio(self):
        if self._audio_proc and self._audio_proc.poll() is None:
            try:
                self._audio_proc.terminate()
            except Exception:
                pass
        self._audio_proc = None

    def draw_content(self, p, inner, t, accent):
        # The dock-tile glyph is drawn by BaseDomainComplication.
        pass

    # ── Cache refresh ─────────────────────────────────────────────────

    def _refresh(self) -> None:
        """Re-extract the headline / topics / gauges from current data.
        Cheap (~ a few ms even with a dozen briefings) but cached every
        20 s so the overlay doesn't re-parse on every frame."""
        from core.state import state

        recent = _load_recent_briefings(limit=12)
        pending = state.pending_briefing
        # Prefer the pending briefing for the headline + supporting bullets,
        # but pull topic frequency from the pending + history.
        primary = pending if pending else (recent[0] if recent else None)

        if primary:
            self._headline = _first_sentence(primary.get("insight") or "")
            self._evidence = list(primary.get("supporting_evidence") or [])
            self._confidence = clamp(float(primary.get("confidence") or 0.5),
                                     0.0, 1.0)
            ts = primary.get("generated_at")
            if ts:
                t_struct = time.localtime(ts)
                self._date_label = time.strftime("%b %d  %H:%M", t_struct).upper()
            else:
                self._date_label = primary.get("date", "").upper()
            self._user_label = (primary.get("user_name") or "").upper()
        else:
            self._headline = "STAND BY — NO BRIEF AVAILABLE"
            self._evidence = ["Awaiting next rumination cycle.",
                              "Tap to refresh."]
            self._confidence = 0.0
            self._date_label = time.strftime("%b %d  %H:%M").upper()
            self._user_label = ""

        # Topic frequency across history + pending
        all_text_parts = []
        if pending:
            all_text_parts.append(pending.get("insight") or "")
            for ev in pending.get("supporting_evidence") or []:
                all_text_parts.append(ev)
        for r in recent:
            all_text_parts.append(r.get("insight") or "")
        all_text = " ".join(all_text_parts)
        self._topics = _extract_topics(all_text, top_n=8)
        self._sentiment = _sentiment_ratio(all_text)
        self._urgency  = _urgency_score(primary)
        self._novelty  = _novelty_score(primary, self._topics)
        self._cache_ts = time.time()

    # ── Main overlay draw ─────────────────────────────────────────────

    def draw_overlay(self, p, cx, cy, mind, t, trans):
        a = clamp(float(trans), 0.0, 1.0)
        if a < 0.002:
            return
        if self._t0 == 0.0:
            self._t0 = t
        elapsed = max(0.0, t - self._t0)

        # Refresh cache occasionally
        if (time.time() - self._cache_ts) > 20.0 or not self._cache_ts:
            self._refresh()

        R = mind * 0.36

        p.save()
        try:
            p.setRenderHint(p.Antialiasing, True)

            # ── Clip to circle ───────────────────────────────────
            clip = QPainterPath()
            clip.addEllipse(QPointF(cx, cy), R, R)
            p.setClipPath(clip)

            # ── Deep navy backdrop with vignette ─────────────────
            bg = QRadialGradient(QPointF(cx, cy), R)
            bg.setColorAt(0.0, _HUD_BG_MID)
            bg.setColorAt(0.7, _HUD_BG_DEEP)
            bg.setColorAt(1.0, QColor(1, 3, 8))
            p.setPen(Qt.NoPen)
            p.setBrush(QBrush(bg))
            p.drawEllipse(QPointF(cx, cy), R, R)

            # Hex grid
            _draw_hex_grid(p, cx, cy, R, t, int(28 * a))

            # Scan line band
            _draw_scan_line(p, cx, cy, R, t, a)

            # ── Bezel — thin cyan ring ───────────────────────────
            bz_pen = QPen(QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                  _HUD_PRIMARY.blue(), int(160 * a)))
            bz_pen.setWidthF(max(1.6, mind * 0.0028))
            p.setPen(bz_pen)
            p.setBrush(Qt.NoBrush)
            p.drawEllipse(QPointF(cx, cy), R * 0.985, R * 0.985)
            inner_pen = QPen(QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                     _HUD_PRIMARY.blue(), int(70 * a)))
            inner_pen.setWidthF(max(1.0, mind * 0.0014))
            p.setPen(inner_pen)
            p.drawEllipse(QPointF(cx, cy), R * 0.94, R * 0.94)

            # ── Top arc: "DAILY BRIEF" ───────────────────────────
            hdr_font = QFont("Helvetica Neue", max(10, int(mind * 0.018)))
            hdr_font.setWeight(QFont.DemiBold)
            hdr_font.setLetterSpacing(QFont.PercentageSpacing, 175)
            _draw_arc_text(p, cx, cy, "DAILY  BRIEF", R * 0.86, -90.0,
                           hdr_font,
                           QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                   _HUD_PRIMARY.blue(), int(245 * a)),
                           spacing_deg=6.5)

            # ── Sub-arc: date / user ─────────────────────────────
            sub_font = QFont("Helvetica Neue", max(7, int(mind * 0.011)))
            sub_font.setWeight(QFont.Medium)
            sub_font.setLetterSpacing(QFont.PercentageSpacing, 165)
            sub_text = self._date_label
            if self._user_label:
                sub_text = f"{self._date_label}  ·  {self._user_label}"
            _draw_arc_text(p, cx, cy, sub_text, R * 0.78, -90.0,
                           sub_font,
                           QColor(_HUD_TEXT_DIM.red(), _HUD_TEXT_DIM.green(),
                                   _HUD_TEXT_DIM.blue(), int(220 * a)),
                           spacing_deg=5.0)

            # ── Headline (typewriter) ────────────────────────────
            h_text = self._headline
            # Reveal one character every 35 ms; hold 5 s when complete.
            chars_per_sec = 28.0
            typed = max(0, min(len(h_text), int(elapsed * chars_per_sec)))
            visible = h_text[:typed]
            cursor_on = (int(elapsed * 2.0) % 2 == 0)
            display = visible + ("▮" if cursor_on else " ")
            head_font = QFont("Helvetica Neue", max(9, int(mind * 0.0145)))
            head_font.setWeight(QFont.Medium)
            head_font.setLetterSpacing(QFont.PercentageSpacing, 115)
            p.setFont(head_font)
            p.setPen(QColor(_HUD_TEXT.red(), _HUD_TEXT.green(),
                             _HUD_TEXT.blue(), int(245 * a)))
            head_rect = QRectF(cx - R * 0.86, cy - R * 0.65,
                                R * 1.72, R * 0.18)
            p.drawText(head_rect, Qt.TextWordWrap | Qt.AlignHCenter | Qt.AlignTop,
                       display)

            # ── Center: topic constellation ──────────────────────
            _draw_constellation(p, cx, cy, R, self._topics, t, a)

            # ── Four sci-fi gauges around the constellation ──────
            gauge_radius = R * 0.085
            gauge_offset = R * 0.62
            # Top-left, top-right, bottom-left, bottom-right
            gauge_positions = [
                (cx - gauge_offset, cy - R * 0.20, "SENTIMENT", self._sentiment, _HUD_OK),
                (cx + gauge_offset, cy - R * 0.20, "URGENCY",   self._urgency,
                 _HUD_DANGER if self._urgency > 0.7 else _HUD_PRIMARY),
                (cx - gauge_offset, cy + R * 0.30, "NOVELTY",   self._novelty, _HUD_PRIMARY),
                (cx + gauge_offset, cy + R * 0.30, "CONFIDENCE", self._confidence,
                 _HUD_OK if self._confidence > 0.6 else _HUD_PRIMARY),
            ]
            for gx, gy, lbl, val, col in gauge_positions:
                _draw_gauge(p, gx, gy, gauge_radius, lbl, val,
                            QColor(col.red(), col.green(), col.blue(),
                                    int(255 * a)),
                            a, t)

            # ── Ticker tape (supporting evidence) ────────────────
            _draw_ticker_tape(p, cx, cy, R, self._evidence, t, a)

            # ── Bottom arc — call-to-action ──────────────────────
            cta_font = QFont("Helvetica Neue", max(7, int(mind * 0.011)))
            cta_font.setWeight(QFont.Medium)
            cta_font.setLetterSpacing(QFont.PercentageSpacing, 175)
            cta_alpha = int(180 * a)
            _draw_arc_text(p, cx, cy, "TAP  TO  HEAR  FULL  BRIEF",
                           R * 0.92, 90.0, cta_font,
                           QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                   _HUD_PRIMARY.blue(), cta_alpha),
                           spacing_deg=4.5, flip=True)

            # ── Decorative corner crosshairs (HUD touch) ─────────
            ch_pen = QPen(QColor(_HUD_PRIMARY.red(), _HUD_PRIMARY.green(),
                                  _HUD_PRIMARY.blue(), int(120 * a)))
            ch_pen.setWidthF(max(1.0, mind * 0.0018))
            p.setPen(ch_pen)
            arm = R * 0.05
            for sign_x in (-1, 1):
                for sign_y in (-1, 1):
                    base_x = cx + sign_x * R * 0.74
                    base_y = cy + sign_y * R * 0.46
                    p.drawLine(QPointF(base_x - arm, base_y),
                               QPointF(base_x + arm, base_y))
                    p.drawLine(QPointF(base_x, base_y - arm),
                               QPointF(base_x, base_y + arm))
        finally:
            p.restore()
